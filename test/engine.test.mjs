test('"Move to Shared" after a routed change shares only that change', async () => {
  const f = folder({ 'settings.shared.json': { 'files.exclude': { a: true } }, 'settings.local.json': { 'files.exclude': { mine: true } } });
  const s = (await sync(f.t, st0, f.ctx, { router: router() })).state;
  write(f.t.settingsFile, { 'files.exclude': { a: true, mine: true, b: true } });
  const r = await sync(f.t, s, f.ctx, { router: router('local') });
  assert.deepEqual(readJson(f.t.localFile), { 'files.exclude': { mine: true, b: true } });
  const [x] = r.routed;
  await sync(f.t, r.state, f.ctx, { router: router(), edit: [{ op: 'shareChange', key: x.key, before: x.previous, after: x.value }] });
  assert.deepEqual(readJson(f.t.sharedFile), { 'files.exclude': { a: true, b: true } });
  assert.deepEqual(readJson(f.t.localFile), { 'files.exclude': { mine: true } });
  assert.deepEqual(readJson(f.t.settingsFile), { 'files.exclude': { a: true, mine: true, b: true } });
});

