test('an edit made while the backup is written is not overwritten: the run starts again and sorts it', async () => {
  const { t, ctx, st } = await setUp({ 'editor.tabSize': 2, a: 1 }, ['a']);
  write(t.sharedFile, { 'editor.tabSize': 4 });
  const take = ctx.backups.take.bind(ctx.backups);
  let once = false;
  ctx.backups.take = async (...args) => {
    const e = await take(...args);
    if (!once) {
      once = true;
      write(t.settingsFile, read(t.settingsFile).replace('{', '{\n    "editor.wordWrap": "on",'));
    }
    return e;
  };
  const r = await sync(t, st, ctx, { router: router() });
  ctx.backups.take = take;
  assert.equal(r.status, 'ok');
  assert.equal(readJson(t.localFile)['editor.wordWrap'], 'on', 'the edit was sorted into the local file');
  assert.deepEqual(readJson(t.settingsFile), { 'editor.tabSize': 4, a: 1, 'editor.wordWrap': 'on' });
});

