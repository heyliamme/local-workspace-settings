// The sync engine in generated mode: setup, merging, routing edits made to settings.json,
// conflicts, backups and undo, no write loops, malformed input, several folders.
import assert from 'node:assert/strict';
import { statSync, writeFileSync, symlinkSync, mkdirSync } from 'fs';
import path from 'path';
import { test } from 'node:test';
import { core, folder, read, readJson, router, tmp, write } from './helpers.mjs';

const { sync, planInit, commitInit, restore } = core;
const st0 = { mode: 'generated' };

async function setUp(settings, personal = []) {
  const f = folder({ 'settings.json': settings });
  const plan = await planInit(f.t, 'generated', personal, f.ctx);
  await commitInit(f.t, plan, f.ctx);
  return { ...f, plan, st: plan.state };
}

test('setup splits settings.json into shared and local, with a preview of each file', async () => {
  const { t, plan } = await setUp('{\n  // team\n  "editor.tabSize": 2,\n  "peacock.color": "#ff0000",\n  "python.defaultInterpreterPath": "/home/me/.venv/bin/python"\n}\n', ['peacock.color', 'python.defaultInterpreterPath']);
  assert.deepEqual(plan.files.map((f) => path.basename(f.path)), ['settings.shared.json', 'settings.local.json', 'settings.json']);
  assert.deepEqual(readJson(t.sharedFile), { 'editor.tabSize': 2 });
  assert.match(read(t.sharedFile), /\/\/ team/);
  assert.deepEqual(readJson(t.localFile), { 'peacock.color': '#ff0000', 'python.defaultInterpreterPath': '/home/me/.venv/bin/python' });
  assert.match(read(t.localFile), /^\/\/ Your own settings, kept out of Git/);
  const gen = read(t.settingsFile);
  assert.match(gen, /^\/\/ Generated by Local Workspace Settings/);
  assert.deepEqual(readJson(t.settingsFile), { 'editor.tabSize': 2, 'peacock.color': '#ff0000', 'python.defaultInterpreterPath': '/home/me/.venv/bin/python' });
});

test('setup refuses when the preview is stale', async () => {
  const f = folder({ 'settings.json': { a: 1 } });
  const plan = await planInit(f.t, 'generated', [], f.ctx);
  write(f.t.settingsFile, { a: 2 });
  await assert.rejects(commitInit(f.t, plan, f.ctx), /changed since the preview/);
  assert.equal((await core.readState(f.t.sharedFile)).exists, false);
});

test('editing the local file updates settings.json; a second run writes nothing', async () => {
  const { t, ctx, st } = await setUp({ 'editor.tabSize': 2, 'files.exclude': { dist: true } });
  write(t.localFile, '{\n  // mine\n  "editor.tabSize": 8,\n  "files.exclude": { "tmp": true }\n}\n');
  const r = await sync(t, st, ctx, { router: router() });
  assert.equal(r.status, 'ok');
  assert.deepEqual(r.wrote, [t.settingsFile]);
  assert.deepEqual(readJson(t.settingsFile), { 'editor.tabSize': 8, 'files.exclude': { dist: true, tmp: true } });
  const mtime = statSync(t.settingsFile).mtimeMs;
  const again = await sync(t, r.state, ctx, { router: router() });
  assert.deepEqual(again.wrote, [], 'no write loop');
  assert.equal(statSync(t.settingsFile).mtimeMs, mtime);
  assert.match(read(t.localFile), /\/\/ mine/, 'the local file is never rewritten by a merge');
});

test('a setting changed in settings.json (Settings editor, another extension) goes to the local file', async () => {
  const { t, ctx, st } = await setUp('{\n  "editor.tabSize": 2\n}\n');
  // What VS Code does when a setting is changed in the UI: edits settings.json in place.
  const text = read(t.settingsFile).replace('"editor.tabSize": 2', '"editor.tabSize": 2,\n    "peacock.color": "#123456"');
  write(t.settingsFile, text);
  const r1 = router();
  const r = await sync(t, st, ctx, { router: r1 });
  assert.deepEqual(r1.asked.map((c) => [c.key, c.value, c.previous]), [['peacock.color', '#123456', undefined]]);
  assert.deepEqual(r.routed, [{ key: 'peacock.color', to: 'local', previous: undefined, value: '#123456' }]);
  assert.deepEqual(readJson(t.localFile), { 'peacock.color': '#123456' });
  assert.deepEqual(readJson(t.sharedFile), { 'editor.tabSize': 2 });
  assert.deepEqual(readJson(t.settingsFile), { 'editor.tabSize': 2, 'peacock.color': '#123456' });
  const again = await sync(t, r.state, ctx, { router: router() });
  assert.deepEqual(again.wrote, []);
});

test('a changed shared setting becomes a local override; resetting it in settings.json removes the setting locally', async () => {
  const { t, ctx, st } = await setUp({ 'editor.tabSize': 2, 'files.exclude': { dist: true, out: true } });
  write(t.settingsFile, { 'files.exclude': { dist: true } });
  const r = await sync(t, st, ctx, { router: router() });
  assert.deepEqual(readJson(t.localFile), { 'editor.tabSize': null, 'files.exclude': { out: null } });
  assert.deepEqual(readJson(t.settingsFile), { 'files.exclude': { dist: true } });
  // Putting the team value back removes the override.
  write(t.settingsFile, { 'editor.tabSize': 2, 'files.exclude': { dist: true, out: true } });
  await sync(t, r.state, ctx, { router: router() });
  assert.deepEqual(readJson(t.localFile), {});
});

test('a change can be routed to the shared file instead, which removes a local override of it', async () => {
  const { t, ctx, st } = await setUp({ a: 1, b: 1 }, ['b']);
  write(t.settingsFile, { a: 5, b: 7 });
  const r = await sync(t, st, ctx, { router: router('shared') });
  assert.deepEqual(readJson(t.sharedFile), { a: 5, b: 7 });
  assert.deepEqual(readJson(t.localFile), {});
  assert.deepEqual(r.routed.map((x) => x.to), ['shared', 'shared']);
});

test('defer leaves every file as it is; discard drops the change (it stays in the backup)', async () => {
  const { t, ctx, st } = await setUp({ a: 1 });
  write(t.settingsFile, { a: 2 });
  const before = read(t.settingsFile);
  const localBefore = read(t.localFile);
  const d = await sync(t, st, ctx, { router: router('defer') });
  assert.equal(d.status, 'pending');
  assert.equal(read(t.settingsFile), before);
  assert.equal(read(t.localFile), localBefore);
  const x = await sync(t, st, ctx, { router: router('discard') });
  assert.deepEqual(readJson(t.settingsFile), { a: 1 });
  assert.equal(await ctx.backups.content(x.backup, t.settingsFile), before);
});

test('the same setting changed in settings.json and in the local file is reported as a conflict', async () => {
  const { t, ctx, st } = await setUp({ a: 1 });
  write(t.localFile, { a: 3 });
  write(t.settingsFile, { a: 2 });
  const r1 = router();
  await sync(t, st, ctx, { router: r1 });
  assert.deepEqual(r1.asked[0].conflict, { layer: 'local', value: 3 });
  assert.deepEqual(readJson(t.localFile), { a: 2 }, 'local was chosen');
});

test('a settings.json from before setup (fresh clone, lost state): unknown edits are asked about', async () => {
  const f = folder({ 'settings.shared.json': { a: 1 }, 'settings.local.json': { b: 2 }, 'settings.json': { a: 1, b: 2, c: 3 } });
  const r1 = router();
  const r = await sync(f.t, st0, f.ctx, { router: r1 });
  assert.deepEqual(r1.asked.map((c) => [c.key, c.unknown]), [['c', true]]);
  assert.deepEqual(readJson(f.t.localFile), { b: 2, c: 3 });
  assert.equal(r.status, 'ok');
  // No settings.json at all: it is simply generated.
  const g = folder({ 'settings.shared.json': { a: 1 } });
  const r2 = router();
  const rg = await sync(g.t, st0, g.ctx, { router: r2 });
  assert.equal(r2.asked.length, 0);
  assert.deepEqual(rg.wrote, [g.t.settingsFile]);
  assert.deepEqual(readJson(g.t.settingsFile), { a: 1 });
});

test('a malformed file is refused and nothing is written', async () => {
  const { t, ctx, st } = await setUp({ a: 1 });
  write(t.localFile, '{ "a": 2, oops }');
  const before = read(t.settingsFile);
  const r = await sync(t, st, ctx, { router: router() });
  assert.equal(r.status, 'error');
  assert.equal(r.file, '.vscode/settings.local.json');
  assert.match(r.message, /can't be read/);
  assert.equal(read(t.settingsFile), before);
  write(t.localFile, '{}');
  write(t.settingsFile, '{ "a": ');
  const r2 = await sync(t, st, ctx, { router: router() });
  assert.equal(r2.status, 'error');
  assert.equal(read(t.settingsFile), '{ "a": ', 'a broken settings.json is not overwritten either');
});

test('every write is backed up first; restore puts the files back and is itself undoable', async () => {
  const { t, ctx, st, backups } = await setUp({ a: 1 });
  write(t.localFile, { a: 2 });
  const r = await sync(t, st, ctx, { router: router() });
  assert.ok(r.backup);
  const list = await backups.list(t.id);
  assert.equal(list[0].id, r.backup.id);
  assert.deepEqual(readJson(t.settingsFile), { a: 2 });
  const s2 = await restore(t, r.state, r.backup, ctx);
  assert.deepEqual(readJson(t.settingsFile), { a: 1 });
  // The restored settings.json is not taken for an edit: the next merge follows the layers.
  const r3 = await sync(t, s2, ctx, { router: router('defer') });
  assert.equal(r3.status, 'ok');
  assert.deepEqual(readJson(t.settingsFile), { a: 2 });
  assert.match((await backups.list(t.id)).map((e) => e.reason).join('|'), /Before restoring/);
});

test('backups rotate', async () => {
  const f = folder({ 'settings.shared.json': { a: 0 } });
  const backups = new core.Backups(path.join(tmp(), 'b'), () => 3);
  const ctx = { backups };
  let st = st0;
  for (let i = 1; i <= 6; i++) {
    write(f.t.localFile, { a: i });
    st = (await sync(f.t, st, ctx, { router: router() })).state;
  }
  assert.equal((await backups.list(f.t.id)).length, 3);
});

test('moves from the overview keep the effective settings the same', async () => {
  const { t, ctx, st } = await setUp({ a: 1, o: { x: 1, y: 2 } });
  write(t.localFile, { o: { y: 3 } });
  let r = await sync(t, st, ctx, { router: router() });
  const eff = readJson(t.settingsFile);
  r = await sync(t, r.state, ctx, { router: router(), edit: [{ op: 'toLocal', key: 'a' }, { op: 'toShared', key: 'o' }] });
  assert.deepEqual(readJson(t.sharedFile), { o: { x: 1, y: 3 } });
  assert.deepEqual(readJson(t.localFile), { a: 1 });
  assert.deepEqual(readJson(t.settingsFile), eff);
  r = await sync(t, r.state, ctx, { router: router(), edit: [{ op: 'removeOverride', key: 'a' }] });
  assert.deepEqual(readJson(t.settingsFile), { o: { x: 1, y: 3 } });
});

